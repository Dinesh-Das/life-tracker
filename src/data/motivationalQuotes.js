function buildThemeQuotes(theme) {
    return theme.stems.flatMap((stem, stemIndex) => theme.finishes.map((finish, finishIndex) => {
        const guideIndex = (stemIndex * theme.finishes.length + finishIndex) % theme.meanings.length;
        return {
            id: `motivation-${theme.key}-${stemIndex + 1}-${finishIndex + 1}`,
            text: `${stem} ${finish}`,
            author: 'LifeTracker Original',
            source: theme.category,
            section: `${theme.inspiredBy}-inspired`,
            sourceUrl: null,
            license: 'Original motivational writing; not official character dialogue or a character quotation.',
            topic: theme.topic,
            category: theme.category,
            inspiredBy: theme.inspiredBy,
            kind: 'original',
            meaning: theme.meanings[guideIndex],
            action: theme.actions[guideIndex],
        };
    }));
}

export const MOTIVATIONAL_QUOTES = Object.freeze(THEMES.flatMap(buildThemeQuotes));
export const MOTIVATIONAL_THEMES = Object.freeze(THEMES.map(({ key, category, topic, inspiredBy }) => ({
    key,
    category,
    topic,
    inspiredBy,
})));
